// scripts/generate.mjs: writes ts/generated.ts from schema/v1/*.json. The JSON Schema files are the source of truth;
// the TypeScript types are a build product and are never edited by hand.
//
//   node scripts/generate.mjs            write ts/generated.ts
//   node scripts/generate.mjs --check    regenerate to a temporary file and diff it against ts/generated.ts; exit 1
//                                        when they differ (a schema changed and the types were not regenerated)
//
// Every schema file is compiled in ONE pass, through one in-memory root that references each file and each of its
// $defs. One pass is what keeps a shared definition (SourceStamp, Id, ...) a single named type: compiling file by file
// would emit it once per file and the concatenation would not typecheck. Referencing every $defs entry keeps a
// definition exported even when no record references it yet.
//
// Reads the schema directory and writes one file. Opens no socket, no device.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// The generator ships as CommonJS. The default import is its module.exports under every Node version; a named import
// would depend on static export detection.
import generator from 'json-schema-to-typescript';

const { compile } = generator;

const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMA_DIR = join(PACKAGE, 'schema', 'v1');
const TARGET = join(PACKAGE, 'ts', 'generated.ts');
const SUFFIX = '.schema.json';
const BANNER = [
  '// Copyright 2026 Shinro SAS. Licensed under the Business Source License 1.1; see LICENSE.',
  '// GENERATED by scripts/generate.mjs from schema/v1/*.json. Do not edit: change the schema, then run `pnpm generate`.',
  '// Keywords without a TypeScript form (pattern, minimum, maximum, if/then, not) are NOT in these types: a value that',
  '// typechecks can still be invalid. The schema decides; validate at the boundary.',
].join('\n');

function root() {
  // Sorted, so that the output does not depend on directory order.
  const stems = readdirSync(SCHEMA_DIR).filter((name) => name.endsWith(SUFFIX)).map((name) => name.slice(0, -SUFFIX.length)).sort();
  if (stems.length === 0) throw new Error(`no ${SUFFIX} file in ${SCHEMA_DIR}`);
  const properties = {};
  for (const stem of stems) {
    const schema = JSON.parse(readFileSync(join(SCHEMA_DIR, stem + SUFFIX), 'utf8'));
    // A file that only holds definitions (common) has no record type of its own.
    if (schema.type !== undefined || schema.oneOf !== undefined) properties[stem] = { $ref: stem + SUFFIX };
    for (const name of Object.keys(schema.$defs ?? {}).sort()) properties[`${stem}__${name}`] = { $ref: `${stem}${SUFFIX}#/$defs/${name}` };
  }
  return {
    title: 'DemoContractsV1',
    description: 'Index of every record and definition of the operator console contract v1. It exists so that one compile reaches everything; nothing sends or receives it.',
    type: 'object',
    additionalProperties: false,
    properties,
  };
}

async function generate() {
  return compile(root(), 'DemoContractsV1', {
    cwd: SCHEMA_DIR + '/', // relative $refs between the schema files resolve against this directory
    bannerComment: BANNER,
    additionalProperties: false, // an object schema that does not say otherwise is closed, as the validators treat the records
    declareExternallyReferenced: true,
    enableConstEnums: false,
    strictIndexSignatures: true,
    unknownAny: true,
    format: true,
    style: { printWidth: 140, singleQuote: true },
  });
}

const check = process.argv.includes('--check');
const unknown = process.argv.slice(2).filter((arg) => arg !== '--check');
if (unknown.length > 0) {
  console.error(`generate: unknown argument ${unknown.join(' ')}; usage: node scripts/generate.mjs [--check]`);
  process.exit(2);
}
const output = await generate();
if (!check) {
  writeFileSync(TARGET, output);
  console.log(`generate: wrote ${TARGET} (${output.split('\n').length} lines)`);
} else {
  if (!existsSync(TARGET)) {
    console.error(`generate --check: ${TARGET} does not exist; run \`pnpm generate\` and commit the result`);
    process.exit(1);
  }
  const scratch = mkdtempSync(join(tmpdir(), 'demo-contracts-check-'));
  try {
    const fresh = join(scratch, 'generated.ts');
    writeFileSync(fresh, output);
    if (readFileSync(TARGET, 'utf8') === output) {
      console.log('generate --check: ts/generated.ts matches the schemas');
    } else {
      const diff = spawnSync('diff', ['-u', TARGET, fresh], { encoding: 'utf8' });
      console.error(diff.error ? 'generate --check: the files differ (no diff tool on PATH to show how)' : diff.stdout);
      console.error('generate --check: ts/generated.ts is stale; run `pnpm generate` and commit the result');
      process.exitCode = 1;
    }
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}
